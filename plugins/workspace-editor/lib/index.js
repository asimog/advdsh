/**
 * Host half of the workspace editor plugin (Stages 3 and 6).
 *
 * Serves the Euro-Office frontend and one host page from this origin, keeps a
 * per-document temp folder, runs x2t for open/save/PDF export, and exposes the
 * `document_edit` tool so the agent can change the same file the editor shows.
 */
import { readFile, stat } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { createDocStore, DocError } from './docs.js'
import { repoRoot, X2tError } from './x2t.js'
import { editDocument, readDocumentText } from './docs-edit.js'

export const name = 'workspace-editor'
export const inject = ['webServer', 'tools']

const ROUTE = '/workspace-editor'
const editorDir = path.join(path.dirname(fileURLToPath(import.meta.url)), 'editor')
/**
 * Editor frontend. The vendored Euro-Office Lite build is the default because
 * it ships the Document Builder the agent engine uses. The release build is an
 * override for a version-matched performance run: set
 * WORKSPACE_EDITOR_FRONTEND to resources/euro-office-de/editors.
 */
const LITE_FRONTEND = path.join(repoRoot, 'resources', 'euro-office')
export const FRONTEND_DIR = process.env.WORKSPACE_EDITOR_FRONTEND ?? LITE_FRONTEND
/** Bundled TTF folder; the release tree ships no fonts of its own. */
const FONT_FALLBACK_DIR = path.join(LITE_FRONTEND, 'fonts')
/** Font cache generated by `x2t -create-allfonts` in the Stage 5 setup. */
const FONTDATA_DIR = path.join(process.env.LOCALAPPDATA ?? '', 'advodsh-eo', 'fontdata')
const GENERATED_ALLFONTS = path.join(FONTDATA_DIR, 'AllFonts.js')

const CONTENT_TYPES = new Map([
  ['.html', 'text/html; charset=utf-8'],
  ['.js', 'text/javascript; charset=utf-8'],
  ['.css', 'text/css; charset=utf-8'],
  ['.json', 'application/json; charset=utf-8'],
  ['.png', 'image/png'],
  ['.jpg', 'image/jpeg'],
  ['.jpeg', 'image/jpeg'],
  ['.gif', 'image/gif'],
  ['.svg', 'image/svg+xml'],
  ['.woff', 'font/woff'],
  ['.woff2', 'font/woff2'],
  ['.ttf', 'font/ttf'],
  ['.eot', 'application/vnd.ms-fontobject'],
  ['.wasm', 'application/wasm'],
  ['.map', 'application/json; charset=utf-8'],
  ['.bin', 'application/octet-stream'],
  ['.pdf', 'application/pdf'],
])

function log(message) {
  console.error(`[workspace-editor] ${message}`)
}

function send(res, status, body, type = 'text/plain; charset=utf-8') {
  res.writeHead(status, { 'content-type': type })
  res.end(body)
}

function sendJson(res, status, value) {
  send(res, status, JSON.stringify(value), 'application/json; charset=utf-8')
}

/**
 * Resolve a request path under a root, refusing anything outside it.
 * @param {string} root - directory the request may read.
 * @param {string} relative - decoded relative path.
 * @returns {string | undefined} absolute path, or undefined when outside the root.
 */
function within(root, relative) {
  const target = path.resolve(root, '.' + path.sep + relative)
  const rootWithSep = path.resolve(root) + path.sep
  return target.startsWith(rootWithSep) ? target : undefined
}

async function serveFile(res, file, cacheControl = 'no-cache') {
  const info = await stat(file).catch(() => undefined)
  if (info === undefined || !info.isFile()) {
    send(res, 404, 'not found')
    return
  }
  const type = CONTENT_TYPES.get(path.extname(file).toLowerCase()) ?? 'application/octet-stream'
  res.writeHead(200, { 'content-type': type, 'cache-control': cacheControl })
  res.end(await readFile(file))
}

/** Read a request body as bytes, capped so a runaway upload cannot exhaust memory. */
async function readBody(req, limit = 512 * 1024 * 1024) {
  const chunks = []
  let size = 0
  for await (const chunk of req) {
    size += chunk.length
    if (size > limit) throw new DocError('document body is too large', { status: 413 })
    chunks.push(chunk)
  }
  return Buffer.concat(chunks)
}

async function readJsonBody(req) {
  const body = await readBody(req, 1024 * 1024)
  return body.length === 0 ? {} : JSON.parse(body.toString('utf8'))
}

function requireId(url) {
  const id = url.searchParams.get('id')
  if (id === null || id === '') throw new DocError('missing document id', { status: 400 })
  return id
}

/** Paths the generated AllFonts.js lists; only those are served as font bytes. */
let fontAllowlist

async function loadFontAllowlist() {
  if (fontAllowlist !== undefined) return fontAllowlist
  const text = await readFile(GENERATED_ALLFONTS, 'utf8').catch(() => '')
  const paths = new Set()
  for (const match of text.matchAll(/"([^"]+\.(?:ttf|otf|ttc))"/gi)) {
    paths.add(path.resolve(match[1].replaceAll('/', path.sep)).toLowerCase())
  }
  fontAllowlist = paths
  return fontAllowlist
}

/**
 * @param {import('@deepseek-ai/cordis').Context} ctx - plugin context.
 */
export function apply(ctx) {
  const store = createDocStore()
  const modified = new Map()

  ctx.effect(() => () => { void store.disposeAll() }, 'workspace-editor.docs')

  const serve = (kind, suffix, handler) => ctx.effect(
    () => ctx.webServer.register({ kind, path: `${ROUTE}${suffix}`, handler }),
    `workspace-editor.route${suffix}`,
  )

  // --- host page and frontend -------------------------------------------------
  serve('exact', '/host.html', async (req, res) => {
    try {
      await serveFile(res, path.join(editorDir, 'host.html'))
    } catch (error) {
      log(`host page failed: ${error instanceof Error ? error.message : error}`)
      send(res, 500, 'cannot read host page')
    }
  })
  serve('exact', '/shim.js', async (_req, res) => { await serveFile(res, path.join(editorDir, 'shim.js')) })
  serve('exact', '/boot.js', async (_req, res) => { await serveFile(res, path.join(editorDir, 'boot.js')) })

  serve('prefix', '/app', async (req, res) => {
    const relative = decodeURIComponent(new URL(req.url, 'http://local').pathname.slice(`${ROUTE}/app/`.length))
    // sdkjs asks for this file by name; the app answers with the font cache the
    // converter generated, which carries the system font list and its selection
    // blob. The static 16-font file next to it cannot render real documents.
    if (relative === 'sdkjs/common/AllFonts.js') {
      const generated = await stat(GENERATED_ALLFONTS).catch(() => undefined)
      if (generated !== undefined) {
        await serveFile(res, GENERATED_ALLFONTS, 'no-cache')
        return
      }
    }
    const file = within(FRONTEND_DIR, relative)
    if (file === undefined) {
      send(res, 403, 'outside the frontend root')
      return
    }
    const bundled = await stat(file).catch(() => undefined)
    if (bundled === undefined && relative.startsWith('fonts/')) {
      const fallback = within(FONT_FALLBACK_DIR, relative.slice('fonts/'.length))
      if (fallback !== undefined) {
        // Immutable: the release build's own files never change under a path.
        await serveFile(res, fallback, 'public, max-age=31536000, immutable')
        return
      }
    }
    await serveFile(res, file, 'public, max-age=31536000, immutable')
  })

  // --- document lifecycle -----------------------------------------------------
  serve('exact', '/api/open', async (req, res) => {
    try {
      const body = await readJsonBody(req)
      if (typeof body.path !== 'string' || body.path === '') throw new DocError('path is required', { status: 400 })
      const doc = await store.open(body.path)
      sendJson(res, 200, doc)
    } catch (error) {
      fail(res, error)
    }
  })

  serve('exact', '/api/info', async (req, res) => {
    try {
      const doc = store.get(requireId(new URL(req.url, 'http://local')))
      const info = await stat(doc.path).catch(() => undefined)
      sendJson(res, 200, {
        id: doc.id,
        name: doc.name,
        kind: doc.kind,
        path: doc.path,
        mtimeMs: info?.mtimeMs ?? 0,
        modified: modified.get(doc.id) ?? false,
      })
    } catch (error) {
      fail(res, error)
    }
  })

  serve('exact', '/api/bin', async (req, res) => {
    try {
      const bytes = await store.bytes(requireId(new URL(req.url, 'http://local')))
      res.writeHead(200, { 'content-type': 'application/octet-stream', 'cache-control': 'no-store' })
      res.end(bytes)
    } catch (error) {
      fail(res, error)
    }
  })

  serve('exact', '/api/save', async (req, res) => {
    try {
      const id = requireId(new URL(req.url, 'http://local'))
      const bytes = await readBody(req)
      const saved = await store.save(id, bytes)
      modified.set(id, false)
      log(`saved ${path.basename(saved.path)} (${bytes.length} bytes)`)
      sendJson(res, 200, saved)
    } catch (error) {
      fail(res, error)
    }
  })

  serve('exact', '/api/save-as', async (req, res) => {
    try {
      const url = new URL(req.url, 'http://local')
      const id = requireId(url)
      const target = url.searchParams.get('path')
      if (target === null || target === '') throw new DocError('path is required', { status: 400 })
      const bytes = await readBody(req)
      const saved = await store.saveAs(id, bytes, target)
      log(`saved as ${saved.path}`)
      sendJson(res, 200, saved)
    } catch (error) {
      fail(res, error)
    }
  })

  serve('exact', '/api/modified', async (req, res) => {
    try {
      const id = requireId(new URL(req.url, 'http://local'))
      const body = await readJsonBody(req)
      modified.set(id, body.modified === true)
      sendJson(res, 200, { modified: modified.get(id) ?? false })
    } catch (error) {
      fail(res, error)
    }
  })

  /** Tab closed: drop the editor session and its temp folder (Editor.bin, media). */
  serve('exact', '/api/close', async (req, res) => {
    try {
      const url = new URL(req.url, 'http://local')
      const id = url.searchParams.get('id') ?? ''
      if (id !== '') {
        modified.delete(id)
        await store.close(id)
      }
      sendJson(res, 200, { closed: id })
    } catch (error) {
      fail(res, error)
    }
  })

  serve('exact', '/api/pdf', async (req, res) => {
    try {
      const id = requireId(new URL(req.url, 'http://local'))
      const pdf = await store.exportPdf(id)
      res.writeHead(200, { 'content-type': 'application/pdf', 'content-disposition': 'inline' })
      res.end(pdf.bytes)
    } catch (error) {
      fail(res, error)
    }
  })

  serve('prefix', '/api/media', async (req, res) => {
    try {
      const relative = decodeURIComponent(new URL(req.url, 'http://local').pathname.slice(`${ROUTE}/api/media/`.length))
      const [docId, ...rest] = relative.split('/')
      const doc = store.get(docId)
      const file = within(path.join(doc.tempDir, 'media'), rest.join('/'))
      if (file === undefined) {
        send(res, 403, 'outside the document media folder')
        return
      }
      await serveFile(res, file)
    } catch (error) {
      fail(res, error)
    }
  })

  serve('exact', '/api/log', async (req, res) => {
    const body = await readBody(req, 64 * 1024)
    if (body.length > 0) log(`page: ${body.toString('utf8').slice(0, 2000)}`)
    send(res, 204, '')
  })

  /** Font bytes for absolute font paths sdkjs knows by name (system fonts). */
  serve('exact', '/api/font', async (req, res) => {
    try {
      const url = new URL(req.url, 'http://local')
      const requested = url.searchParams.get('path')
      if (requested === null || requested === '') throw new DocError('path is required', { status: 400 })
      const absolute = path.resolve(requested.replace(/^[/\\]\?[/\\]?/, '').replaceAll('/', path.sep))
      if (!/\.(ttf|otf|ttc)$/i.test(absolute)) throw new DocError('not a font file', { status: 400 })
      const allowlist = await loadFontAllowlist()
      if (!allowlist.has(absolute.toLowerCase())) throw new DocError('font is not in the generated font list', { status: 403 })
      await serveFile(res, absolute)
    } catch (error) {
      fail(res, error)
    }
  })

  // --- agent-facing tool ------------------------------------------------------
  ctx.effect(() => ctx.tools.register({
    name: 'document_edit',
    description: 'Read or change a Word document (.docx) in the workspace. '
      + 'With no edit fields it returns the document text. '
      + '`find`/`replace` change text, `append` adds a paragraph at the end, and `set_paragraph` replaces one paragraph by index. '
      + 'The editor tab of an open document reloads the file when it has no unsaved changes.',
    parameters: {
      type: 'object',
      properties: {
        path: { type: 'string', description: 'Absolute path to a .docx file.' },
        find: { type: 'string', description: 'Text to find (case-sensitive, inside one text run).' },
        replace: { type: 'string', description: 'Replacement text for `find`.' },
        append: { type: 'string', description: 'Paragraph text appended at the end of the document.' },
        set_paragraph: {
          type: 'object',
          description: 'Replace the text of one paragraph by zero-based body index.',
          properties: {
            index: { type: 'number' },
            text: { type: 'string' },
          },
          required: ['index', 'text'],
          additionalProperties: false,
        },
      },
      required: ['path'],
      additionalProperties: false,
    },
    output: {
      schema: {
        type: 'object',
        properties: {
          path: { type: 'string' },
          changed: { type: 'boolean' },
          paragraphs: { type: 'number' },
          text: { type: 'string' },
        },
        required: ['path', 'changed', 'paragraphs', 'text'],
        additionalProperties: false,
      },
      render: (_args, value) => [{
        type: 'text',
        text: value.changed
          ? `changed ${value.path} (${value.paragraphs} paragraphs)`
          : value.text,
      }],
    },
    async execute(args) {
      const request = /** @type {{ path: string, find?: string, replace?: string, append?: string, set_paragraph?: { index: number, text: string } }} */ (args)
      if (typeof request.path !== 'string' || request.path === '') throw new DocError('path is required', { status: 400 })
      const hasEdit = request.find !== undefined || request.append !== undefined || request.set_paragraph !== undefined
      if (!hasEdit) {
        const text = await readDocumentText(request.path)
        return { path: path.resolve(request.path), changed: false, paragraphs: 0, text }
      }
      const result = await editDocument(request.path, {
        find: request.find,
        replace: request.replace,
        append: request.append,
        setParagraph: request.set_paragraph,
      })
      return { path: result.path, changed: true, paragraphs: result.paragraphs, text: '' }
    },
  }), 'workspace-editor.tool')

  /** Map a store or converter failure to a named HTTP error. */
  function fail(res, error) {
    if (error instanceof DocError) {
      sendJson(res, error.status, { error: error.message })
      return
    }
    if (error instanceof X2tError) {
      log(`x2t: ${error.message}\n${error.stderr}`)
      sendJson(res, 500, { error: error.message, stderr: error.stderr.slice(0, 4000) })
      return
    }
    log(`route failure: ${error instanceof Error ? error.stack ?? error.message : String(error)}`)
    sendJson(res, 500, { error: error instanceof Error ? error.message : String(error) })
  }
}
