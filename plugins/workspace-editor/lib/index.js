/**
 * Host half of the workspace editor plugin.
 *
 * Serves the Euro-Office frontend and one host page from this origin, keeps a
 * per-document temp folder, runs x2t for open/save/PDF export, and provides
 * `ctx.editorDocuments`: the document/revision authority shared by the editor
 * tab, the host page and agent tools. Every route is fenced by the
 * composition's `connection` service when it exists. `GET /workspace-editor/events`
 * is the SSE channel a tab or host page subscribes to for document, editor and
 * command frames. All document writes go through `ctx.editorDocuments`; the
 * retired whole-file `document_edit` writer is not registered.
 */
import { randomUUID } from 'node:crypto'
import { readFile, stat } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { createDocStore, DocError } from './docs.js'
import { repoRoot, X2tError } from './x2t.js'
import { ERROR_CODES, routeErrorBody, statusFor } from './errors.js'
import { sessionIdFromRequest } from './scope.js'

export const name = 'workspace-editor'
export const inject = ['webServer', 'tools']

const ROUTE = '/workspace-editor'
const editorDir = path.join(path.dirname(fileURLToPath(import.meta.url)), 'editor')
/**
 * Editor frontend. The vendored Euro-Office Lite build is the default because
 * it ships the Document Builder the agent engine uses. The release build is an
 * override for a version-matched performance run: set
 * WORKSPACE_EDITOR_FRONTEND to resources/euro-office-de/editors.
 */
const LITE_FRONTEND = path.join(repoRoot, 'resources', 'euro-office')
export const FRONTEND_DIR = process.env.WORKSPACE_EDITOR_FRONTEND ?? LITE_FRONTEND
/** Bundled TTF folder; the release tree ships no fonts of its own. */
const FONT_FALLBACK_DIR = path.join(LITE_FRONTEND, 'fonts')
/** Font cache generated by `x2t -create-allfonts` in the Stage 5 setup. */
const FONTDATA_DIR = path.join(process.env.LOCALAPPDATA ?? '', 'advodsh-eo', 'fontdata')
const GENERATED_ALLFONTS = path.join(FONTDATA_DIR, 'AllFonts.js')
/** SSE keep-alive comment interval; comments keep idle connections from timing out. */
const SSE_HEARTBEAT_MS = 25_000
/** Review commands the host page executes through the editor API. */
const REVIEW_COMMANDS = new Set([
  'acceptAll',
  'rejectAll',
  'acceptSelection',
  'rejectSelection',
  'nextChange',
  'prevChange',
  'displayMode',
  'trackChanges',
])

const CONTENT_TYPES = new Map([
  ['.html', 'text/html; charset=utf-8'],
  ['.js', 'text/javascript; charset=utf-8'],
  ['.css', 'text/css; charset=utf-8'],
  ['.json', 'application/json; charset=utf-8'],
  ['.png', 'image/png'],
  ['.jpg', 'image/jpeg'],
  ['.jpeg', 'image/jpeg'],
  ['.gif', 'image/gif'],
  ['.svg', 'image/svg+xml'],
  ['.woff', 'font/woff'],
  ['.woff2', 'font/woff2'],
  ['.ttf', 'font/ttf'],
  ['.eot', 'application/vnd.ms-fontobject'],
  ['.wasm', 'application/wasm'],
  ['.map', 'application/json; charset=utf-8'],
  ['.bin', 'application/octet-stream'],
  ['.pdf', 'application/pdf'],
])

function log(message) {
  console.error(`[workspace-editor] ${message}`)
}

function send(res, status, body, type = 'text/plain; charset=utf-8') {
  res.writeHead(status, { 'content-type': type })
  res.end(body)
}

function sendJson(res, status, value) {
  send(res, status, JSON.stringify(value), 'application/json; charset=utf-8')
}

/** One SSE data frame; the JSON carries the frame type. */
function sseData(frame) {
  return `data: ${JSON.stringify(frame)}\n\n`
}

/**
 * Resolve a request path under a root, refusing anything outside it.
 * @param {string} root - directory the request may read.
 * @param {string} relative - decoded relative path.
 * @returns {string | undefined} absolute path, or undefined when outside the root.
 */
function within(root, relative) {
  const target = path.resolve(root, '.' + path.sep + relative)
  const rootWithSep = path.resolve(root) + path.sep
  return target.startsWith(rootWithSep) ? target : undefined
}

async function serveFile(res, file, cacheControl = 'no-cache') {
  const info = await stat(file).catch(() => undefined)
  if (info === undefined || !info.isFile()) {
    send(res, 404, 'not found')
    return
  }
  const type = CONTENT_TYPES.get(path.extname(file).toLowerCase()) ?? 'application/octet-stream'
  res.writeHead(200, { 'content-type': type, 'cache-control': cacheControl })
  res.end(await readFile(file))
}

/** Read a request body as bytes, capped so a runaway upload cannot exhaust memory. */
async function readBody(req, limit = 512 * 1024 * 1024) {
  const chunks = []
  let size = 0
  for await (const chunk of req) {
    size += chunk.length
    if (size > limit) throw new DocError('document body is too large', { status: 413 })
    chunks.push(chunk)
  }
  return Buffer.concat(chunks)
}

async function readJsonBody(req) {
  const body = await readBody(req, 1024 * 1024)
  if (body.length === 0) return {}
  try {
    return JSON.parse(body.toString('utf8'))
  } catch (error) {
    throw new DocError('invalid JSON body', { status: 400, code: ERROR_CODES.INVALID_ARGS })
  }
}

/** Refuse a JSON body with a field the route does not read. */
function rejectUnknown(body, allowed) {
  for (const key of Object.keys(body)) {
    if (!allowed.includes(key)) throw new DocError(`unknown field: ${key}`, { status: 400, code: ERROR_CODES.INVALID_ARGS })
  }
}

function requireId(url) {
  const id = url.searchParams.get('id')
  if (id === null || id === '') throw new DocError('missing document id', { status: 400 })
  return id
}

/** The revision a save/save-as is based on, from the query string or a header. */
function baseOf(url, req) {
  const query = url.searchParams.get('base')
  if (query !== null && query !== '') return query
  const header = req.headers['x-workspace-editor-base']
  const value = Array.isArray(header) ? header[0] : header
  return typeof value === 'string' && value !== '' ? value : undefined
}

/** Paths the generated AllFonts.js lists; only those are served as font bytes. */
let fontAllowlist

async function loadFontAllowlist() {
  if (fontAllowlist !== undefined) return fontAllowlist
  const text = await readFile(GENERATED_ALLFONTS, 'utf8').catch(() => '')
  const paths = new Set()
  for (const match of text.matchAll(/"([^"]+\.(?:ttf|otf|ttc))"/gi)) {
    paths.add(path.resolve(match[1].replaceAll('/', path.sep)).toLowerCase())
  }
  fontAllowlist = paths
  return fontAllowlist
}

/**
 * @param {import('@deepseek-ai/cordis').Context} ctx - plugin context.
 */
export function apply(ctx) {
  /** Open SSE responses and the DSH session each connection belongs to. */
  const connections = new Map()
  /** The composition's trust fence, optional in headless harness runs. */
  const trust = ctx.get('connection')
  /** @type {ReturnType<typeof createDocStore>} */
  let docs

  /** Write one frame to every live SSE client. @param {object} frame - frame payload. */
  function broadcast(frame) {
    const line = sseData(frame)
    const framePath = typeof frame.path === 'string'
      ? frame.path
      : (frame.document && typeof frame.document.path === 'string' ? frame.document.path : '')
    for (const [res, sessionId] of connections) {
      if (sessionId !== undefined && framePath !== '' && !ownsPath(sessionId, framePath)) continue
      try {
        res.write(line)
      } catch {
        // A closing client is removed by its own close handler; the frame is lost for it.
      }
    }
  }

  /** @param {string} sessionId - DSH session. @param {string} file - document path. @returns {boolean} owned. */
  function ownsPath(sessionId, file) {
    const key = path.resolve(file).toLowerCase()
    const model = ctx.get('docxModel')
    if (model !== undefined && typeof model.status === 'function') {
      const owned = model.status(undefined, sessionId).some((session) => path.resolve(session.path).toLowerCase() === key)
      if (owned) return true
    }
    return docs.list().some((document) => document.ownerSessionId === sessionId && path.resolve(document.path).toLowerCase() === key)
  }

  /** Emit a Cordis fact the future document model consumes; a missing listener is legal. */
  function emit(event, payload) {
    try {
      ctx.emit(event, payload)
    } catch (error) {
      log(`${event} listener failed: ${error instanceof Error ? error.message : error}`)
    }
  }

  /**
   * Refuse an untrusted request before any route work. The `connection`
   * service owns the Host/Origin fence and browser authentication; without it
   * (a headless composition) an explicit cross-origin browser call is refused.
   * @param {import('node:http').IncomingMessage} req - request.
   * @param {import('node:http').ServerResponse} res - response owned here when refused.
   * @returns {boolean} true when the request was answered.
   */
  function rejected(req, res) {
    if (trust !== undefined && typeof trust.requestRejection === 'function') {
      const rejection = trust.requestRejection(req)
      if (rejection === undefined) return false
      res.writeHead(rejection)
      res.end()
      return true
    }
    const origin = req.headers.origin
    if (typeof origin !== 'string' || origin === '') return false
    let sameOrigin = false
    try {
      sameOrigin = new URL(origin).host === new URL(`http://${req.headers.host ?? ''}`).host
    } catch {
      // A malformed Origin cannot match this listener; it is refused below.
    }
    if (sameOrigin) return false
    res.writeHead(403)
    res.end()
    return true
  }

  docs = createDocStore({
    store: ctx.get('editorDocumentsStore'),
    workspaceRoot: ctx.get('workspaceRoot') ?? process.cwd(),
    allowedRoots: (process.env.WORKSPACE_DOCX_ALLOWED_ROOTS ?? '').split(path.delimiter).filter(Boolean),
    onEvent: (event) => {
      if (event.type === 'document') {
        broadcast({
          type: 'document',
          source: event.source,
          document: event.document,
          reload: event.reload === true,
          closed: event.closed === true,
        })
        return
      }
      if (event.type === 'editor') {
        broadcast({ type: 'editor', document: event.document, command: event.command, ok: event.ok === true })
        return
      }
      if (event.type === 'conflict') {
        broadcast({ type: 'conflict', path: event.path, base: event.base, current: event.current, code: event.code })
        emit('editor-documents/conflict', {
          path: event.path,
          base: event.base,
          current: event.current,
          code: event.code,
        })
        return
      }
      if (event.type === 'saved') {
        emit('editor-documents/saved', { path: event.path, revision: event.revision })
      }
    },
  })

  ctx.effect(() => () => { void docs.disposeAll() }, 'workspace-editor.docs')

  /**
   * Broadcast one review command to the host pages; the page owning the
   * document executes it through the editor API and reports the result back on
   * `POST /api/editor`.
   * @param {{ id?: string, path?: string, command: string, args?: unknown }} request - command request.
   */
  /** Pending editor-open requests per DSH session. */
  const pendingOpens = new Map()
  /** Command request ids waiting for a host-page acknowledgement. */
  const commandWaiters = new Map()
  function dispatchCommand(request) {
    const requestId = randomUUID()
    broadcast({ type: 'command', id: request.id, requestId, path: request.path, command: request.command, args: request.args })
    const delivered = connections.size
    if (request.awaitAck !== true) return { delivered, command: request.command, executed: delivered > 0 }
    return new Promise((resolve) => {
      const timer = setTimeout(() => {
        commandWaiters.delete(requestId)
        resolve({ delivered, command: request.command, executed: false, timedOut: true })
      }, 10000)
      commandWaiters.set(requestId, { resolve, timer, delivered, command: request.command })
    })
  }

  /** The service consumed by the document model and agent tool rows. */
  const editorDocuments = {
    /** @param {string} file - document path. */
    open: (file, options) => docs.open(file, options),
    /** @param {string} id - document id. */
    info: (id) => docs.info(id),
    /** @returns {object[]} open document views. */
    list: () => docs.list(),
    /** @param {string} id - document id. */
    readBytes: (id) => docs.readBytes(id),
    /** @param {string} file - document path. @param {Uint8Array} bytes - document bytes. @param {object} [options] - lease terms. */
    applyBytes: (file, bytes, options) => docs.applyBytes(file, bytes, options),
    /** @param {string} id - document id. @param {Uint8Array} bytes - editor bytes. @param {object} [options] - base revision. */
    save: (id, bytes, options) => docs.save(id, bytes, options),
    /** @param {string} id - document id. @param {Uint8Array} bytes - editor bytes. @param {string} target - destination. @param {object} [options] - base revision. */
    saveAs: (id, bytes, target, options) => docs.saveAs(id, bytes, target, options),
    history: (id) => docs.history(id),
    /** @param {string} id - document id. @param {object} patch - editor report. */
    setEditorState: (id, patch) => docs.setEditorState(id, patch),
    /** @param {string} target - document id or path. @param {object} [options] - baseline revision and deadline. */
    wait: (target, options) => docs.wait(target, options),
    /** @param {string} id - document id. */
    exportPdf: (id) => docs.exportPdf(id),
    /** @param {string} id - document id. */
    close: (id) => docs.close(id),
    /** @param {object} request - review command request. */
    command: (request) => dispatchCommand(request),
    requestOpen: (sessionId, file) => {
      if (typeof sessionId !== 'string' || sessionId === '' || typeof file !== 'string' || file === '') return { queued: false }
      const list = pendingOpens.get(sessionId) ?? []
      list.push(file)
      pendingOpens.set(sessionId, list)
      return { queued: true }
    },
  }
  ctx.effect(() => ctx.provide('editorDocuments', editorDocuments), 'workspace-editor.editorDocuments')

  /** Routes that mutate state; every other route is read-only. */
  const POST_ROUTES = new Set(['/api/open', '/api/save', '/api/save-as', '/api/close', '/api/editor', '/api/command'])
  /** Register one route behind the trust fence. */
  const serve = (kind, suffix, handler) => ctx.effect(
    () => ctx.webServer.register({
      kind,
      path: `${ROUTE}${suffix}`,
      handler: (req, res) => {
        if (rejected(req, res)) return
        const post = POST_ROUTES.has(suffix)
        if ((post && req.method !== 'POST') || (!post && req.method !== 'GET' && req.method !== 'HEAD')) {
          sendJson(res, 405, { error: 'method not allowed', code: ERROR_CODES.INVALID_ARGS })
          return
        }
        return handler(req, res)
      },
    }),
    `workspace-editor.route${suffix}`,
  )

  // --- host page and frontend -------------------------------------------------
  serve('exact', '/host.html', async (_req, res) => {
    try {
      res.setHeader('content-security-policy', "default-src 'none'; script-src 'self' 'unsafe-inline' 'unsafe-eval'; worker-src 'self' blob:; style-src 'self' 'unsafe-inline'; img-src 'self' data: blob:; font-src 'self' data:; connect-src 'self'; frame-src 'self'; child-src 'self' blob:")
      await serveFile(res, path.join(editorDir, 'host.html'))
    } catch (error) {
      log(`host page failed: ${error instanceof Error ? error.message : error}`)
      send(res, 500, 'cannot read host page')
    }
  })
  serve('exact', '/shim.js', async (_req, res) => { await serveFile(res, path.join(editorDir, 'shim.js')) })
  serve('exact', '/boot.js', async (_req, res) => { await serveFile(res, path.join(editorDir, 'boot.js')) })

  serve('prefix', '/app', async (req, res) => {
    const relative = decodeURIComponent(new URL(req.url, 'http://local').pathname.slice(`${ROUTE}/app/`.length))
    // sdkjs asks for this file by name; the app answers with the font cache the
    // converter generated, which carries the system font list and its selection
    // blob. The static 16-font file next to it cannot render real documents.
    if (relative === 'sdkjs/common/AllFonts.js') {
      const generated = await stat(GENERATED_ALLFONTS).catch(() => undefined)
      if (generated !== undefined) {
        await serveFile(res, GENERATED_ALLFONTS, 'no-cache')
        return
      }
    }
    const file = within(FRONTEND_DIR, relative)
    if (file === undefined) {
      send(res, 403, 'outside the frontend root')
      return
    }
    const bundled = await stat(file).catch(() => undefined)
    if (bundled === undefined && relative.startsWith('fonts/')) {
      const fallback = within(FONT_FALLBACK_DIR, relative.slice('fonts/'.length))
      if (fallback !== undefined) {
        // Immutable: the release build's own files never change under a path.
        await serveFile(res, fallback, 'public, max-age=31536000, immutable')
        return
      }
    }
    await serveFile(res, file, 'public, max-age=31536000, immutable')
  })

  // --- SSE channel ------------------------------------------------------------
  // Snapshot first, then document/editor/command frames. The connection is
  // force-closed on plugin disposal, because an SSE response never ends itself.
  ctx.effect(() => {
    const disposeRoute = ctx.webServer.register({
      kind: 'exact',
      path: `${ROUTE}/events`,
      handler: (req, res) => {
        if (rejected(req, res)) return
        if (req.method !== 'GET') {
          res.writeHead(405, { allow: 'GET' })
          res.end()
          return
        }
        res.writeHead(200, {
          'content-type': 'text/event-stream; charset=utf-8',
          'cache-control': 'no-cache, no-transform',
          'connection': 'keep-alive',
          'x-accel-buffering': 'no',
        })
        res.write(': connected\n\n')
        const sessionId = sessionIdFromRequest(req)
        res.write(sseData({ type: 'snapshot', documents: docs.list().filter((document) => sessionId === undefined || !document.ownerSessionId || document.ownerSessionId === sessionId) }))
        connections.set(res, sessionId)
        const heartbeat = setInterval(() => {
          try {
            res.write(': ping\n\n')
          } catch {
            // The close handler removes a dead connection; the interval is cleared there.
          }
        }, SSE_HEARTBEAT_MS)
        heartbeat.unref?.()
        const release = () => {
          clearInterval(heartbeat)
          connections.delete(res)
        }
        req.on('close', release)
        res.on('close', release)
      },
    })
    return () => {
      disposeRoute()
      for (const res of connections.keys()) res.destroy()
      connections.clear()
    }
  }, 'workspace-editor.events')

  /** @param {string | undefined} sessionId - DSH session. @returns {string | undefined} its workspace root. */
  function sessionCwd(sessionId) {
    if (sessionId === undefined) return undefined
    const model = ctx.get('docxModel')
    if (model === undefined || typeof model.status !== 'function') return undefined
    const row = model.status(undefined, sessionId)[0]
    return row && typeof row.cwd === 'string' && row.cwd !== '' ? row.cwd : undefined
  }

  /** Refuse a document id that does not belong to the request's DSH session. */
  async function assertDocOwner(req, id) {
    const sessionId = sessionIdFromRequest(req)
    if (sessionId === undefined) return
    const view = await docs.info(id)
    if (!ownsPath(sessionId, view.path)) {
      throw new DocError('document not found in this session', { status: 404, code: ERROR_CODES.SESSION_NOT_FOUND })
    }
  }
  ctx.on('session/disposed', (session) => {
    if (session && typeof session.id === 'string') void docs.closeOwner(session.id)
  })

  /** Pending editor-open requests for one DSH session; consumed by the client. */
  serve('exact', '/api/pending-open', async (req, res) => {
    try {
      const sessionId = sessionIdFromRequest(req)
      if (sessionId === undefined) throw new DocError('session is required', { status: 400, code: ERROR_CODES.INVALID_ARGS })
      const paths = pendingOpens.get(sessionId) ?? []
      pendingOpens.delete(sessionId)
      sendJson(res, 200, { paths })
    } catch (error) {
      fail(res, error)
    }
  })
  // --- document lifecycle -----------------------------------------------------
  serve('exact', '/api/open', async (req, res) => {
    try {
      const body = await readJsonBody(req)
      rejectUnknown(body, ['path'])
      if (typeof body.path !== 'string' || body.path === '') throw new DocError('path is required', { status: 400 })
      const sessionId = sessionIdFromRequest(req)
      sendJson(res, 200, await docs.open(body.path, { cwd: sessionCwd(sessionId), sessionId }))
    } catch (error) {
      fail(res, error)
    }
  })

  serve('exact', '/api/info', async (req, res) => {
    try {
      const id = requireId(new URL(req.url, 'http://local'))
      await assertDocOwner(req, id)
      sendJson(res, 200, await docs.info(id))
    } catch (error) {
      fail(res, error)
    }
  })

  serve('exact', '/api/bin', async (req, res) => {
    try {
      const id = requireId(new URL(req.url, 'http://local'))
      await assertDocOwner(req, id)
      const opened = await docs.readBytes(id)
      res.writeHead(200, {
        'content-type': 'application/octet-stream',
        'cache-control': 'no-store',
        'x-workspace-editor-revision': opened.revision,
      })
      res.end(opened.bytes)
    } catch (error) {
      fail(res, error)
    }
  })

  serve('exact', '/api/save', async (req, res) => {
    try {
      const url = new URL(req.url, 'http://local')
      const id = requireId(url)
      await assertDocOwner(req, id)
      const bytes = await readBody(req)
      const saved = await docs.save(id, bytes, { base: baseOf(url, req) })
      log(`saved ${path.basename(saved.path)} revision ${saved.revision.slice(0, 12)} (${bytes.length} bytes)`)
      sendJson(res, 200, saved)
    } catch (error) {
      fail(res, error)
    }
  })

  serve('exact', '/api/save-as', async (req, res) => {
    try {
      const url = new URL(req.url, 'http://local')
      const id = requireId(url)
      await assertDocOwner(req, id)
      const target = url.searchParams.get('path')
      if (target === null || target === '') throw new DocError('path is required', { status: 400 })
      const bytes = await readBody(req)
      const saved = await docs.saveAs(id, bytes, target, {
        base: baseOf(url, req),
        overwrite: url.searchParams.get('overwrite') === 'true',
        cwd: sessionCwd(sessionIdFromRequest(req)),
      })
      log(`saved as ${saved.path} revision ${saved.revision.slice(0, 12)}`)
      sendJson(res, 200, saved)
    } catch (error) {
      fail(res, error)
    }
  })

  /**
   * Editor state report from the host page: unsaved changes, the revision the
   * tab loaded, and the outcome of a review command it executed.
   */
  serve('exact', '/api/editor', async (req, res) => {
    try {
      const body = await readJsonBody(req)
      rejectUnknown(body, ['id', 'modified', 'revision', 'command', 'ok', 'requestId', 'path'])
      if (typeof body.id !== 'string' || body.id === '') throw new DocError('id is required', { status: 400 })
      await assertDocOwner(req, body.id)
      if (typeof body.requestId === 'string') {
        const waiter = commandWaiters.get(body.requestId)
        if (waiter !== undefined) {
          clearTimeout(waiter.timer)
          commandWaiters.delete(body.requestId)
          waiter.resolve({
            delivered: waiter.delivered,
            command: waiter.command,
            executed: body.ok !== false,
            changeCount: Number.isInteger(body.changeCount) ? body.changeCount : 0,
          })
        }
      }
      sendJson(res, 200, docs.setEditorState(body.id, {
        modified: body.modified,
        revision: body.revision,
        command: body.command,
        ok: body.ok,
      }))
    } catch (error) {
      fail(res, error)
    }
  })

  /** Host-page review commands are relayed to the open host page over SSE. */
  serve('exact', '/api/command', async (req, res) => {
    try {
      const body = await readJsonBody(req)
      const command = typeof body.command === 'string' ? body.command : ''
      if (!REVIEW_COMMANDS.has(command)) {
        throw new DocError(`unknown editor command: ${command === '' ? '(missing)' : command}`, { status: 400 })
      }
      const id = typeof body.id === 'string' && body.id !== '' ? body.id : undefined
      if (id !== undefined) { await assertDocOwner(req, id); await docs.info(id) }
      const target = typeof body.path === 'string' && body.path !== '' ? body.path : undefined
      sendJson(res, 200, await dispatchCommand({ id, path: target, command, args: body.args, awaitAck: body.awaitAck === true }))
    } catch (error) {
      fail(res, error)
    }
  })

  serve('exact', '/api/modified', async (req, res) => {
    try {
      const id = requireId(new URL(req.url, 'http://local'))
      await assertDocOwner(req, id)
      const body = await readJsonBody(req)
      sendJson(res, 200, docs.setEditorState(id, { modified: body.modified === true }))
    } catch (error) {
      fail(res, error)
    }
  })

  /** Tab closed: drop the editor session and its temp folder (Editor.bin, media). */
  serve('exact', '/api/close', async (req, res) => {
    try {
      const id = new URL(req.url, 'http://local').searchParams.get('id') ?? ''
      if (id !== '') { await assertDocOwner(req, id); await docs.close(id) }
      sendJson(res, 200, { closed: id })
    } catch (error) {
      fail(res, error)
    }
  })

  serve('exact', '/api/pdf', async (req, res) => {
    try {
      const id = requireId(new URL(req.url, 'http://local'))
      await assertDocOwner(req, id)
      const pdf = await docs.exportPdf(id)
      res.writeHead(200, { 'content-type': 'application/pdf', 'content-disposition': 'inline' })
      res.end(pdf.bytes)
    } catch (error) {
      fail(res, error)
    }
  })

  serve('prefix', '/api/media', async (req, res) => {
    try {
      const relative = decodeURIComponent(new URL(req.url, 'http://local').pathname.slice(`${ROUTE}/api/media/`.length))
      const [docId, ...rest] = relative.split('/')
      const doc = docs.get(docId)
      const file = within(path.join(doc.tempDir, 'media'), rest.join('/'))
      if (file === undefined) {
        send(res, 403, 'outside the document media folder')
        return
      }
      await serveFile(res, file)
    } catch (error) {
      fail(res, error)
    }
  })

  serve('exact', '/api/log', async (req, res) => {
    const body = await readBody(req, 64 * 1024)
    if (body.length > 0) log(`page: ${body.toString('utf8').slice(0, 2000)}`)
    send(res, 204, '')
  })

  /** Font bytes for absolute font paths sdkjs knows by name (system fonts). */
  serve('exact', '/api/font', async (req, res) => {
    try {
      const url = new URL(req.url, 'http://local')
      const requested = url.searchParams.get('path')
      if (requested === null || requested === '') throw new DocError('path is required', { status: 400 })
      const absolute = path.resolve(requested.replace(/^[/\\]\?[/\\]?/, '').replaceAll('/', path.sep))
      if (!/\.(ttf|otf|ttc)$/i.test(absolute)) throw new DocError('not a font file', { status: 400 })
      const allowlist = await loadFontAllowlist()
      if (!allowlist.has(absolute.toLowerCase())) throw new DocError('font is not in the generated font list', { status: 403 })
      await serveFile(res, absolute)
    } catch (error) {
      fail(res, error)
    }
  })

  // The document write authority is `ctx.editorDocuments`; the old
  // `document_edit` whole-file writer is intentionally not registered.

  /** Map a store or converter failure to the route error body. */
  function fail(res, error) {
    const body = routeErrorBody(error)
    if (error instanceof DocError) {
      sendJson(res, error.status ?? statusFor(body.code), body)
      return
    }
    if (error instanceof X2tError) {
      log(`x2t: ${error.message}\n${error.stderr}`)
      sendJson(res, 500, { ...body, code: ERROR_CODES.COMMIT_FAILED, stderr: error.stderr.slice(0, 4000) })
      return
    }
    if (error && typeof error.code === 'string' && error.code.startsWith('DOC_')) {
      sendJson(res, statusFor(error.code, 500), body)
      return
    }
    log(`route failure: ${error instanceof Error ? error.stack ?? error.message : String(error)}`)
    sendJson(res, 500, body)
  }
}


